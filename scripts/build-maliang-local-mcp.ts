import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const checkOnly = process.argv.includes("--check");
const outputPath = "distribution/codex-marketplace/plugins/maliang-image-generator/mcp/maliang-local-mcp.mjs";
const result = await build({
  entryPoints: ["scripts/maliang-local-mcp-entry.mjs"],
  outfile: outputPath,
  bundle: true, platform: "node", format: "esm", target: "node20", minify: true, charset: "utf8",
  // Preserve SDK template-string data while avoiding whitespace-only lines in the generated artifact.
  supported: { "template-literal": false },
  legalComments: "inline", metafile: true, write: false,
  external: ["../skills/maliang-image-generator/scripts/maliang-helper.mjs"],
  banner: { js: '// Generated by bun run build:maliang-local-mcp. Edit scripts/maliang-local-mcp-entry.mjs.\nimport { createRequire as __maliangCreateRequire } from "node:module"; const require = __maliangCreateRequire(import.meta.url);' }
});
const packages = new Set(Object.keys(result.metafile!.inputs).flatMap((file) => {
  const match = file.replaceAll("\\", "/").match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  return match ? [match[1]!] : [];
}));
const notices: string[] = [];
for (const name of [...packages].sort()) {
  const root = path.join("node_modules", name);
  const manifest = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
  let license = "";
  for (const file of ["LICENSE", "LICENSE.md", "LICENSE.txt", "license", "license.md"]) {
    try { license = await readFile(path.join(root, file), "utf8"); break; } catch {}
  }
  if (!license) throw new Error(`Bundled dependency ${name} has no license notice`);
  notices.push(`${name} ${manifest.version}\n${license.replaceAll("\r\n", "\n")}`);
}
const artifacts = [
  [outputPath, result.outputFiles![0]!.text],
  ["distribution/codex-marketplace/plugins/maliang-image-generator/mcp/THIRD_PARTY_NOTICES.txt", notices.join("\n\n---\n\n")]
] as const;
for (const [file, content] of artifacts) {
  if (checkOnly) {
    if ((await readFile(file, "utf8")).replaceAll("\r\n", "\n") !== content) throw new Error(`${file} is stale; run bun run build:maliang-local-mcp`);
  } else await writeFile(file, content);
}
console.log(`${checkOnly ? "Verified" : "Bundled"} local MCP with ${packages.size} dependency notices.`);
