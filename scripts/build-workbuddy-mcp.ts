import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const outputPath = "scripts/maliang-workbuddy-mcp.mjs";
const noticesPath = "scripts/WORKBUDDY_MCP_NOTICES.txt";
const checkOnly = process.argv.includes("--check");
const result = await build({
  entryPoints: ["scripts/maliang-workbuddy-mcp-entry.mjs"], outfile: outputPath,
  bundle: true, platform: "node", format: "esm", target: "node20", minify: true, charset: "utf8",
  supported: { "template-literal": false }, legalComments: "inline", metafile: true, write: false,
  banner: { js: '// Generated by bun run build:workbuddy-mcp. Edit scripts/maliang-workbuddy-mcp-entry.mjs.\nimport { createRequire as __maliangCreateRequire } from "node:module"; const require = __maliangCreateRequire(import.meta.url);' }
});
const packages = new Set(Object.keys(result.metafile.inputs).flatMap((file) => {
  const match = file.replaceAll("\\", "/").match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  return match ? [match[1]!] : [];
}));
const notices = [];
for (const name of [...packages].sort()) {
  const root = path.join("node_modules", name);
  const manifest = JSON.parse(await readFile(path.join(root, "package.json"), "utf8"));
  let license = "";
  for (const file of ["LICENSE", "LICENSE.md", "LICENSE.txt", "license", "license.md"]) {
    try { license = await readFile(path.join(root, file), "utf8"); break; } catch {}
  }
  if (!license) throw new Error(`Bundled dependency ${name} has no license notice`);
  notices.push(`${name} ${manifest.version}\n${license.replaceAll("\r\n", "\n")}`);
}
for (const [file, content] of [[outputPath, result.outputFiles[0]!.text], [noticesPath, notices.join("\n\n---\n\n")]] as const) {
  if (checkOnly) {
    if ((await readFile(file, "utf8")).replaceAll("\r\n", "\n") !== content) throw new Error(`${file} is stale; run bun run build:workbuddy-mcp`);
  } else await writeFile(file, content);
}
console.log(`${checkOnly ? "Verified" : "Bundled"} WorkBuddy MCP with ${packages.size} dependency notices.`);
